    private void btntambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btntambahActionPerformed
        // TODO add your handling code here:
        String KodeBuku, JudulBuku, Penulis, TahunTerbit, Genre;
        KodeBuku = kode_buku.getText();
        JudulBuku = judul_buku.getText();
        Penulis = penulis.getText();
        TahunTerbit = tahun_terbit.getText();
        Genre="";
        if(komedi.isSelected()== true){
            Genre = "Komedi";
        } 
        if (action.isSelected()==true){
            Genre = "Action";
        }
        else {
            Genre = "Horor";
        }
        
        model.addRow(new Object [] {KodeBuku, JudulBuku, Penulis, TahunTerbit, Genre});
        tabelbuku.setModel(model);
    }//GEN-LAST:event_btntambahActionPerformed

