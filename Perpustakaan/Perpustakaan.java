    private void btnSimpanSiswaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanSiswaActionPerformed
        // TODO add your handling code here:
        String NIS, NamaSiswa, Kelas, Jurusan;
        NIS = txtNIS.getText();
        NamaSiswa = txtNama.getText();
        Kelas = txtKelas.getText();
        Jurusan = "";
        if (rbRPL.isSelected()== true){
            Jurusan = "RPL";
        }
        if (rbTKJ.isSelected()== true){
            Jurusan = "TKJ";
        }
        if (rbDKV.isSelected()== true){
            Jurusan = "DKV";
        }
        if (rbANM.isSelected()== true){
            Jurusan = "Animasi";
        }
        if (rbPHT.isSelected()== true){
            Jurusan = "Perhotelan";
        } else{
            Jurusan = "Kuliner";
        }
        
        model2.addRow(new Object[]{NIS, NamaSiswa, Kelas, Jurusan});
        tabelsiswa.setModel(model2);
    }//GEN-LAST:event_btnSimpanSiswaActionPerformed

